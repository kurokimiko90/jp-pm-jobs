export type Room3DText = (typeof ROOM3D_UI)[VNLang];

export const roomLabel = (id: RoomId, lang: VNLang): string => {
  const room = ROOMS.find((r) => r.id === id);
  if (!room) return id;
  return lang === 'ja' ? room.labelJa : room.labelZh;
};

/** 幕タイトルが「第一幕　開場」のように既に幕番号を含むなら二重に付けない */
export const actLabel = (ui: Room3DText, i: number, title: string): string =>
  /^第.{1,3}幕/.test(title) ? title : `${ui.act.replace('{n}', String(i + 1))}　${title}`;
